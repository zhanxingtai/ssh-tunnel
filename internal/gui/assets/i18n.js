// currentLang is the language of the interface.
let currentLang = 'zh-CN';

// t returns the message of the given key in the language in use.
function t(key) {
  const dict = I18N[currentLang] || I18N['zh-CN'];
  if (dict[key] !== undefined) return dict[key];
  const fallback = I18N['zh-CN'];
  return fallback[key] !== undefined ? fallback[key] : key;
}

// setLang switches the language of the interface.
function setLang(lang) {
  if (I18N[lang]) currentLang = lang;
}

// applyI18n writes the messages of the language in use into the elements
// marked with data-i18n.
function applyI18n() {
  document.documentElement.lang = currentLang;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const text = t(el.dataset.i18nTitle);
    el.title = text;
    el.setAttribute('aria-label', text);
  });
}
